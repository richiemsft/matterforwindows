TEST(WindowsBoringSslCryptoPAL, NegativeInputBoundaries)
{
    DefaultSessionKeystore keystore;
    Symmetric128BitsKeyByteArray keyMaterial = { 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47,
                                                 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f };
    Aes128KeyHandle key;
    ASSERT_CHIP_OK(keystore.CreateKey(keyMaterial, key));

    const uint8_t nonce[kAES_CCM128_Nonce_Length] = { 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16,
                                                      0x17, 0x18, 0x19, 0x1a, 0x1b, 0x1c };
    const uint8_t aad[]       = { 0x00, 0x01, 0x02, 0x03 };
    const uint8_t plaintext[] = { 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27 };
    uint8_t ciphertext[sizeof(plaintext)];
    uint8_t tag[kAES_CCM128_Tag_Length];

    // Zero nonce length is invalid for AES-CCM encryption and decryption.
    EXPECT_EQ(AES_CCM_encrypt(plaintext, sizeof(plaintext), aad, sizeof(aad), key, nonce, 0, ciphertext, tag, sizeof(tag)),
              CHIP_ERROR_INVALID_ARGUMENT);
    EXPECT_EQ(AES_CCM_decrypt(ciphertext, sizeof(ciphertext), aad, sizeof(aad), tag, sizeof(tag), key, nonce, 0, ciphertext),
              CHIP_ERROR_INVALID_ARGUMENT);

    // A tag length outside the valid AES-CCM range is rejected.
    EXPECT_EQ(AES_CCM_encrypt(plaintext, sizeof(plaintext), aad, sizeof(aad), key, nonce, sizeof(nonce), ciphertext, tag, 13),
              CHIP_ERROR_INVALID_ARGUMENT);

    keystore.DestroyKey(key);

    // ECDSA: signing a zero-length message and validating a zero-length message
    // or signature must fail rather than crash.
    P256Keypair keypair;
    ASSERT_CHIP_OK(keypair.Initialize(ECPKeyTarget::ECDSA));
    const uint8_t message[] = { 'b', 'o', 'u', 'n', 'd', 's' };
    P256ECDSASignature signature;

    EXPECT_NE(keypair.ECDSA_sign_msg(nullptr, 0, signature), CHIP_NO_ERROR);
    EXPECT_NE(keypair.ECDSA_sign_msg(message, 0, signature), CHIP_NO_ERROR);

    ASSERT_CHIP_OK(keypair.ECDSA_sign_msg(message, sizeof(message), signature));
    EXPECT_NE(keypair.Pubkey().ECDSA_validate_msg_signature(nullptr, 0, signature), CHIP_NO_ERROR);
    EXPECT_NE(keypair.Pubkey().ECDSA_validate_msg_signature(message, 0, signature), CHIP_NO_ERROR);

    // DRBG must reject a null output buffer with non-zero length.
    EXPECT_NE(DRBG_get_bytes(nullptr, 16), CHIP_NO_ERROR);
}

