// -------------------------------------------------------------------------
// P-256 key import from raw bits (NIST ECDSA2VS KeyPair.rsp vectors, reused
// from P256_test_vectors.h). Validates InitializeFromBitsOrReject against the
// published (d, Qx, Qy) tuples and the curve-order acceptance boundary.
// -------------------------------------------------------------------------

TEST(WindowsBoringSslCryptoPAL, P256InitializeFromBitsKnownAnswers)
{
    P256Keypair keypair;

    uint8_t bits[kP256_PrivateKey_Length];
    for (const auto & tv : p256_test_vectors)
    {
        static_assert(sizeof(bits) == sizeof(tv.d), "private key size mismatch");
        memcpy(bits, tv.d, sizeof(bits));

        // Valid d values are in [1, N-1]; FIPS 186-5 A.4.2 computes d = x + 1 for
        // x in [0, N-2]. Decrement by one to obtain the x the import expects.
        // None of these vectors have an LSB of 0, so no borrow handling needed.
        ASSERT_NE(bits[kP256_PrivateKey_Length - 1], 0);
        bits[kP256_PrivateKey_Length - 1] = static_cast<uint8_t>(bits[kP256_PrivateKey_Length - 1] - 1);

        keypair.Clear();
        ASSERT_CHIP_OK(keypair.InitializeFromBitsOrReject(FixedByteSpan<kP256_PrivateKey_Length>(bits)));

        // Reconstruct the expected serialized keypair (0x04 || Qx || Qy || d).
        P256SerializedKeypair expected;
        uint8_t * p = expected.Bytes();
        *p++        = 0x04;
        memcpy(p, tv.Qx, sizeof(tv.Qx));
        p += sizeof(tv.Qx);
        memcpy(p, tv.Qy, sizeof(tv.Qy));
        p += sizeof(tv.Qy);
        memcpy(p, tv.d, sizeof(tv.d));
        p += sizeof(tv.d);
        ASSERT_EQ(expected.Bytes() + expected.Capacity(), p);
        ASSERT_CHIP_OK(expected.SetLength(expected.Capacity()));

        P256SerializedKeypair actual;
        ASSERT_CHIP_OK(keypair.Serialize(actual));
        EXPECT_TRUE(actual.Span().data_equal(expected.Span()));
    }

    // Boundary around the curve order N: values up to and including N-2 are
    // valid (after the +1 they map to [1, N-1]); N-1 and above are rejected.
    static constexpr uint8_t kP256CurveOrder[kP256_PrivateKey_Length] = {
        0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
        0xbc, 0xe6, 0xfa, 0xad, 0xa7, 0x17, 0x9e, 0x84, 0xf3, 0xb9, 0xca, 0xc2, 0xfc, 0x63, 0x25, 0x51
    };

    for (int ofs = -4; ofs < 2; ofs++)
    {
        memcpy(bits, kP256CurveOrder, sizeof(bits));
        bits[kP256_PrivateKey_Length - 1] = static_cast<uint8_t>(bits[kP256_PrivateKey_Length - 1] + ofs);

        keypair.Clear();
        CHIP_ERROR expected = (ofs <= -2) ? CHIP_NO_ERROR : CHIP_ERROR_INVALID_ARGUMENT;
        EXPECT_EQ(keypair.InitializeFromBitsOrReject(FixedByteSpan<kP256_PrivateKey_Length>(bits)), expected);
    }

    // All-ones is well above N and must be rejected.
    memset(bits, 0xff, sizeof(bits));
    keypair.Clear();
    EXPECT_EQ(keypair.InitializeFromBitsOrReject(FixedByteSpan<kP256_PrivateKey_Length>(bits)), CHIP_ERROR_INVALID_ARGUMENT);
}

