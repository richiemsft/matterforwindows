TEST(WindowsBoringSslCryptoPAL, Spake2pRfcKnownAnswer)
{
    uint8_t L[kMAX_Point_Length];
    uint8_t Z[kMAX_Point_Length];
    uint8_t V[kMAX_Point_Length];
    uint8_t X[kMAX_Point_Length];
    uint8_t Y[kMAX_Point_Length];
    uint8_t Pverifier[kMAX_Hash_Length];
    uint8_t Vverifier[kMAX_Hash_Length];

    const int numOfTestVectors = static_cast<int>(sizeof(kSpakeRfcVectors) / sizeof(kSpakeRfcVectors[0]));
    int numOfTestsRan          = 0;
    for (int vectorIndex = 0; vectorIndex < numOfTestVectors; vectorIndex++)
    {
        const Spake2pRfcTestVector * vector = &kSpakeRfcVectors[vectorIndex];

        TestSpake2p Prover;
        TestSpake2p Verifier;

        ASSERT_CHIP_OK(Prover.Init(vector->context, vector->context_len));
        ASSERT_CHIP_OK(Prover.BeginProver(vector->prover_identity, vector->prover_identity_len, vector->verifier_identity,
                                          vector->verifier_identity_len, vector->w0, vector->w0_len, vector->w1, vector->w1_len));
        ASSERT_CHIP_OK(Prover.TestSetFE(vector->x, vector->x_len));

        size_t X_len = sizeof(X);
        ASSERT_CHIP_OK(Prover.ComputeRoundOne(nullptr, 0, X, &X_len));
        EXPECT_EQ(X_len, vector->X_len);
        EXPECT_EQ(memcmp(X, vector->X, vector->X_len), 0);

        ASSERT_CHIP_OK(Verifier.Init(vector->context, vector->context_len));

        size_t L_len = sizeof(L);
        ASSERT_CHIP_OK(Verifier.ComputeL(L, &L_len, vector->w1, vector->w1_len));
        EXPECT_EQ(L_len, vector->L_len);
        EXPECT_EQ(memcmp(L, vector->L, vector->L_len), 0);

        ASSERT_CHIP_OK(Verifier.BeginVerifier(vector->verifier_identity, vector->verifier_identity_len, vector->prover_identity,
                                              vector->prover_identity_len, vector->w0, vector->w0_len, L, L_len));
        ASSERT_CHIP_OK(Verifier.TestSetFE(vector->y, vector->y_len));

        size_t Y_len = sizeof(Y);
        ASSERT_CHIP_OK(Verifier.ComputeRoundOne(X, X_len, Y, &Y_len));
        EXPECT_EQ(Y_len, vector->Y_len);
        EXPECT_EQ(memcmp(Y, vector->Y, vector->Y_len), 0);

        size_t Vverifier_len = sizeof(Vverifier);
        ASSERT_CHIP_OK(Verifier.ComputeRoundTwo(X, X_len, Vverifier, &Vverifier_len));
        EXPECT_EQ(Vverifier_len, vector->MAC_KcB_len);
        EXPECT_EQ(memcmp(Vverifier, vector->MAC_KcB, vector->MAC_KcB_len), 0);

        ASSERT_CHIP_OK(Verifier.PointWrite(Verifier.Z, Z, kP256_Point_Length));
        EXPECT_EQ(memcmp(Z, vector->Z, vector->Z_len), 0);
        ASSERT_CHIP_OK(Verifier.PointWrite(Verifier.V, V, kP256_Point_Length));
        EXPECT_EQ(memcmp(V, vector->V, vector->V_len), 0);

        size_t Pverifier_len = sizeof(Pverifier);
        ASSERT_CHIP_OK(Prover.ComputeRoundTwo(Y, Y_len, Pverifier, &Pverifier_len));
        EXPECT_EQ(Pverifier_len, vector->MAC_KcA_len);
        EXPECT_EQ(memcmp(Pverifier, vector->MAC_KcA, vector->MAC_KcA_len), 0);

        // Both parties confirm the other's key contribution.
        ASSERT_CHIP_OK(Prover.KeyConfirm(Vverifier, Vverifier_len));
        ASSERT_CHIP_OK(Verifier.KeyConfirm(Pverifier, Pverifier_len));

        // Both parties derive the same HKDF key as the vector. The key handles
        // are opaque, so compare the derived attestation challenges instead.
        DefaultSessionKeystore keystore;
        HkdfKeyHandle vectorKe;
        ASSERT_CHIP_OK(keystore.CreateKey(ByteSpan(vector->Ke, vector->Ke_len), vectorKe));

        auto challengeOf = [&](const HkdfKeyHandle & key, AttestationChallenge & challenge) {
            Aes128KeyHandle i2r;
            Aes128KeyHandle r2i;
            ASSERT_CHIP_OK(keystore.DeriveSessionKeys(key, ByteSpan::fromCharString("TESTSALT"),
                                                      ByteSpan::fromCharString("TESTINFO"), i2r, r2i, challenge));
            keystore.DestroyKey(i2r);
            keystore.DestroyKey(r2i);
        };

        AttestationChallenge expectedChallenge;
        challengeOf(vectorKe, expectedChallenge);

        HkdfKeyHandle proverKe;
        ASSERT_CHIP_OK(Prover.GetKeys(keystore, proverKe));
        AttestationChallenge proverChallenge;
        challengeOf(proverKe, proverChallenge);
        EXPECT_EQ(memcmp(proverChallenge.ConstBytes(), expectedChallenge.ConstBytes(), AttestationChallenge::Length()), 0);

        HkdfKeyHandle verifierKe;
        ASSERT_CHIP_OK(Verifier.GetKeys(keystore, verifierKe));
        AttestationChallenge verifierChallenge;
        challengeOf(verifierKe, verifierChallenge);
        EXPECT_EQ(memcmp(verifierChallenge.ConstBytes(), expectedChallenge.ConstBytes(), AttestationChallenge::Length()), 0);

        keystore.DestroyKey(vectorKe);
        keystore.DestroyKey(proverKe);
        keystore.DestroyKey(verifierKe);
        numOfTestsRan++;
    }
    EXPECT_GT(numOfTestsRan, 0);
    EXPECT_EQ(numOfTestsRan, numOfTestVectors);
}

TEST(WindowsBoringSslCryptoPAL, Spake2pFullHandshakeAgreement)
{
    // Full protocol run with real random ephemeral scalars (no monkey-patching):
    // prover and verifier must reach mutual key confirmation and derive an equal
    // shared key. w0/w1 are the SPAKE2+ RFC draft-01 sample PBKDF outputs.
    static const uint8_t w0[] = { 0xe6, 0x88, 0x7c, 0xf9, 0xbd, 0xfb, 0x75, 0x79, 0xc6, 0x9b, 0xf4,
                                  0x79, 0x28, 0xa8, 0x45, 0x14, 0xb5, 0xe3, 0x55, 0xac, 0x03, 0x48,
                                  0x63, 0xf7, 0xff, 0xaf, 0x43, 0x90, 0xe6, 0x7d, 0x79, 0x8c };
    static const uint8_t w1[] = { 0x24, 0xb5, 0xae, 0x4a, 0xbd, 0xa8, 0x68, 0xec, 0x93, 0x36, 0xff,
                                  0xc3, 0xb7, 0x8e, 0xe3, 0x1c, 0x57, 0x55, 0xbe, 0xf1, 0x75, 0x92,
                                  0x27, 0xef, 0x53, 0x72, 0xca, 0x13, 0x9b, 0x94, 0xe5, 0x12 };
    const uint8_t proverId[]   = { 'c', 'l', 'i', 'e', 'n', 't' };
    const uint8_t verifierId[] = { 's', 'e', 'r', 'v', 'e', 'r' };

    Spake2p_P256_SHA256_HKDF_HMAC prover;
    Spake2p_P256_SHA256_HKDF_HMAC verifier;

    ASSERT_CHIP_OK(prover.Init(nullptr, 0));
    ASSERT_CHIP_OK(verifier.Init(nullptr, 0));

    uint8_t L[kMAX_Point_Length];
    size_t L_len = sizeof(L);
    ASSERT_CHIP_OK(verifier.ComputeL(L, &L_len, w1, sizeof(w1)));

    ASSERT_CHIP_OK(
        prover.BeginProver(proverId, sizeof(proverId), verifierId, sizeof(verifierId), w0, sizeof(w0), w1, sizeof(w1)));
    ASSERT_CHIP_OK(
        verifier.BeginVerifier(verifierId, sizeof(verifierId), proverId, sizeof(proverId), w0, sizeof(w0), L, L_len));

    uint8_t X[kMAX_Point_Length];
    size_t X_len = sizeof(X);
    ASSERT_CHIP_OK(prover.ComputeRoundOne(nullptr, 0, X, &X_len));

    uint8_t Y[kMAX_Point_Length];
    size_t Y_len = sizeof(Y);
    ASSERT_CHIP_OK(verifier.ComputeRoundOne(X, X_len, Y, &Y_len));

    uint8_t proverConfirm[kMAX_Hash_Length];
    size_t proverConfirmLen = sizeof(proverConfirm);
    ASSERT_CHIP_OK(prover.ComputeRoundTwo(Y, Y_len, proverConfirm, &proverConfirmLen));

    uint8_t verifierConfirm[kMAX_Hash_Length];
    size_t verifierConfirmLen = sizeof(verifierConfirm);
    ASSERT_CHIP_OK(verifier.ComputeRoundTwo(X, X_len, verifierConfirm, &verifierConfirmLen));

    // A tampered confirmation must be rejected while the prover is still in
    // the round-two state, before a successful confirmation changes its state.
    uint8_t tampered[kMAX_Hash_Length];
    memcpy(tampered, verifierConfirm, verifierConfirmLen);
    tampered[0] = static_cast<uint8_t>(tampered[0] ^ 0x01);
    EXPECT_NE(prover.KeyConfirm(tampered, verifierConfirmLen), CHIP_NO_ERROR);

    ASSERT_CHIP_OK(prover.KeyConfirm(verifierConfirm, verifierConfirmLen));
    ASSERT_CHIP_OK(verifier.KeyConfirm(proverConfirm, proverConfirmLen));

    // Both sides derived the same shared key (compare via attestation challenge).
    DefaultSessionKeystore keystore;
    HkdfKeyHandle proverKey;
    HkdfKeyHandle verifierKey;
    ASSERT_CHIP_OK(prover.GetKeys(keystore, proverKey));
    ASSERT_CHIP_OK(verifier.GetKeys(keystore, verifierKey));

    auto challengeOf = [&](const HkdfKeyHandle & key, AttestationChallenge & challenge) {
        Aes128KeyHandle i2r;
        Aes128KeyHandle r2i;
        ASSERT_CHIP_OK(keystore.DeriveSessionKeys(key, ByteSpan::fromCharString("SALT1234"),
                                                  ByteSpan::fromCharString("INFO1234"), i2r, r2i, challenge));
        keystore.DestroyKey(i2r);
        keystore.DestroyKey(r2i);
    };

    AttestationChallenge proverChallenge;
    AttestationChallenge verifierChallenge;
    challengeOf(proverKey, proverChallenge);
    challengeOf(verifierKey, verifierChallenge);
    EXPECT_EQ(memcmp(proverChallenge.ConstBytes(), verifierChallenge.ConstBytes(), AttestationChallenge::Length()), 0);

    keystore.DestroyKey(proverKey);
    keystore.DestroyKey(verifierKey);
}

