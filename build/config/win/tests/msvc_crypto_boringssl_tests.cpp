    DefaultSessionKeystore keystore;

    P256ECDHDerivedSecret ecdhSecret;
    memcpy(ecdhSecret.Bytes(), secret, strlen(secret));
    ASSERT_CHIP_OK(ecdhSecret.SetLength(strlen(secret)));

    Aes128KeyHandle key;
    ASSERT_CHIP_OK(keystore.DeriveKey(ecdhSecret, ByteSpan::fromCharString("salt123"), ByteSpan::fromCharString("info123"), key));

