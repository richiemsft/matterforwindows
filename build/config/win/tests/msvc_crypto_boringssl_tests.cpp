/**
 *    @file
 *      Focused native-MSVC correctness tests for the repository-pinned BoringSSL
 *      CryptoPAL (chip_crypto="boringssl", OPENSSL_NO_ASM).
 *
 *      These tests drive the real CryptoPAL primitives through their public
 *      Matter API and check them against authoritative published known-answer
 *      vectors (NIST FIPS 180-4, RFC 4231, RFC 5869, RFC 6070/7914, RFC 6979,
 *      RFC 3686, the SPAKE2+ draft-01 RFC vectors, and the NIST ECDSA2VS P-256
 *      key-pair vectors) plus algebraic correctness properties. They cover
 *      hashing (one-shot and streaming), HMAC, HKDF, PBKDF2, AES-CCM AEAD,
 *      AES-CTR, ECDSA signatures/keypairs, deterministic ECDSA (RFC 6979),
 *      ECDH key agreement, the DRBG, constant-time comparison, P-256 keypair
 *      serialization/deserialization and bit-import, PKCS#10 CSR generation and
 *      verification, X.509 public-key extraction, the SPAKE2+ handshake
 *      (RFC known-answer and full mutual agreement), the DefaultSessionKeystore
 *      derive/export/destroy surface, and negative input boundaries.
 *
 *      Vector sourcing: the upstream src/crypto/tests vector headers express
 *      their data with C++20 designated initializers (and some use zero-length
 *      arrays for empty messages/salts/AAD), neither of which MSVC accepts under
 *      the repository-required C++17 standard. Rather than override the standard
 *      for this translation unit, the needed known-answer vectors are reproduced
 *      locally with C++17 positional aggregate initialization, copied verbatim
 *      from the upstream sources -- specifically the NIST ECDSA2VS P-256
 *      KeyPair.rsp tuples (P256_test_vectors.h) and the SPAKE2+ draft-01 RFC
 *      vectors (SPAKE2P_RFC_test_vectors.h). The remaining vectors are likewise
 *      inlined from their upstream sources, or live in TestChipCryptoPAL.cpp
 *      itself. The upstream GoogleTest suites additionally pull the
 *      credentials/CHIPCert closure and lib/core/StringBuilderAdapters.h
 *      (Pigweed pw_string), neither of which is a Windows closure yet, so those
 *      suites remain blocked; this driver exercises the same real CryptoPAL
 *      implementation in the meantime.
 */

