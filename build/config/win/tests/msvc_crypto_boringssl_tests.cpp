TEST(WindowsBoringSslCryptoPAL, SessionKeystoreOpaqueBytesExportRoundTrip)
{
    // The raw key store exposes key material as opaque bytes so it can be
    // persisted and restored. A handle restored from another handle's opaque
    // bytes must reference the same key.
    Symmetric128BitsKeyByteArray keyMaterial = { 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47,
                                                 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f };
    const uint8_t nonce[13]                  = { 0xf0, 0x0d };
    const uint8_t plaintext[16]              = { 0xca, 0xfe };

    DefaultSessionKeystore keystore;
    Aes128KeyHandle original;
    ASSERT_CHIP_OK(keystore.CreateKey(keyMaterial, original));

    Aes128KeyHandle restored;
    ASSERT_EQ(original.OpaqueBytes().size(), Aes128KeyHandle::Size());
    memcpy(restored.OpaqueBytes().data(), original.OpaqueBytes().data(), Aes128KeyHandle::Size());

    uint8_t ciphertext[16];
    ASSERT_CHIP_OK(AES_CTR_crypt(plaintext, sizeof(plaintext), original, nonce, sizeof(nonce), ciphertext));
    uint8_t recovered[16];
    ASSERT_CHIP_OK(AES_CTR_crypt(ciphertext, sizeof(ciphertext), restored, nonce, sizeof(nonce), recovered));
    EXPECT_EQ(memcmp(recovered, plaintext, sizeof(plaintext)), 0);

    // Raw-key handles contain independent copies and must each be destroyed.
    keystore.DestroyKey(restored);
    keystore.DestroyKey(original);
}

